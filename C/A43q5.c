////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Program      : Recursive Pattern Demo (Small Letters)
// Input        : f
// Output       : a b c d e f
// Functions    : Display()
// Description  : Prints small letters from a to given letter recursively
// Author       : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

void Display(char ch)
{
    if(ch <= 'f')
    {
        printf("%c ",ch);
        Display(ch + 1);
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Prints small letters using recursion.
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cEnd;

    printf("Enter last small letter : ");
    scanf(" %c",&cEnd);

    Display('a');

    return 0;
}
