////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Program      : Recursive Pattern Demo (Numbers Decreasing)
// Input        : 5
// Output       : 5 4 3 2 1
// Functions    : Display()
// Description  : Prints numbers from given number down to 1 recursively
// Author       : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

void Display(int iNo)
{
    if(iNo > 0)
    {
        printf("%d ",iNo);
        Display(iNo - 1);
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Prints numbers in decreasing order using recursion.
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number : ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}
