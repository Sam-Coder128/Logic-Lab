////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Program      : Recursive Pattern Demo (Numbers Increasing)
// Input        : 5
// Output       : 1 2 3 4 5
// Functions    : Display()
// Description  : Prints numbers from 1 to given number recursively
// Author       : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

void Display(int iNo)
{
    static int i = 1;
    if(i <= iNo)
    {
        printf("%d ",i);
        i++;
        Display(iNo);
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Prints numbers in increasing order using recursion.
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number : ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}
