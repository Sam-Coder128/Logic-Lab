////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Program      : Recursive Pattern Demo (Stars)
// Input        : 5
// Output       : * * * * *
// Functions    : Display()
// Description  : Prints stars recursively for given number
// Author       : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

void Display(int iNo)
{
    if(iNo > 0)
    {
        printf("* ");
        Display(iNo - 1);
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Prints stars pattern using recursion.
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number of stars : ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}
