////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Program      : Recursive Pattern Demo (Capital Letters)
// Input        : F
// Output       : A B C D E F
// Functions    : Display()
// Description  : Prints capital letters from A to given letter recursively
// Author       : Samruddh Shivkumar Birajdar
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

void Display(char ch)
{
    if(ch <= 'F')
    {
        printf("%c ",ch);
        Display(ch + 1);
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Prints capital letters using recursion.
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cEnd;

    printf("Enter last capital letter : ");
    scanf(" %c",&cEnd);

    Display('A');

    return 0;
}
